export function getGallery(slug: string) {
  return galleries.find((gallery) => gallery.slug === slug);
}

export function getAdjacentGalleries(slug: string) {
  const index = galleries.findIndex((gallery) => gallery.slug === slug);
  if (index === -1) {
    return { previous: undefined, next: undefined };
  }
  return {
    previous: galleries[(index - 1 + galleries.length) % galleries.length],
    next: galleries[(index + 1) % galleries.length],
  };
}
